"""Generate src/test/data/p256_spend_vector.json: one NIP-060 §5 spend shared
by the Python signer, the C++ tests and device firmware.

It fixes the transaction, the input, the spent output (amount and
scriptPubKey, which the transaction alone does not carry), the exact message
TXHASH || spent scriptPubKey || amount, the 32-byte digest a device signs, and
a deterministic signature by a test key. A device that applies one SHA-256
too many signs SHA-256(digest) instead: its signature verifies over the
digest as a message, not over the message.

Usage: gen_spend_vector.py > src/test/data/p256_spend_vector.json
"""

import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', '..', 'test', 'functional'))
import p256_sign  # noqa: E402
from test_framework import key_p256 as k  # noqa: E402
from test_framework.messages import COutPoint, CTransaction, CTxIn, CTxOut  # noqa: E402


def main():
    # The seeds keep the provisional label NIP-XX: the published spend vector
    # (src/test/data/p256_spend_vector.json) was derived from them.
    priv = int.from_bytes(hashlib.sha256(b'NIP-XX spend vector key').digest(), 'big') % k.N
    pub = k.pubkey_from_privkey(priv)
    script = p256_sign.witness_script(pub)
    spent_spk = b'\x51\x20' + p256_sign.authscript_program(script)
    amount = 123456789

    tx = CTransaction()
    tx.nVersion = 2
    tx.nLockTime = 0
    prev0 = int.from_bytes(hashlib.sha256(b'NIP-XX spend vector prevout 0').digest(), 'little')
    prev1 = int.from_bytes(hashlib.sha256(b'NIP-XX spend vector prevout 1').digest(), 'little')
    tx.vin = [CTxIn(COutPoint(prev0, 1), b'', 0xfffffffe), CTxIn(COutPoint(prev1, 0), b'', 0xffffffff)]
    payee = b'\x76\xa9\x14' + bytes(range(20)) + b'\x88\xac'
    tx.vout = [CTxOut(100000000, payee), CTxOut(23000000, b'\x51\x20' + bytes(range(32, 64)))]
    unsigned = tx.serialize_without_witness().hex()

    msg = p256_sign.message(tx, 0, amount, spent_spk)
    digest = hashlib.sha256(msg).digest()
    sig = k.sign(priv, msg)
    assert k.verify(pub, msg, sig)
    # The double-hash mistake: the device hashes the digest again.
    wrong = k.sign_digest(priv, hashlib.sha256(digest).digest())
    assert not k.verify(pub, msg, wrong) and k.verify(pub, digest, wrong)

    signed = p256_sign.with_witness(tx, 0, sig, script).serialize_with_witness().hex()
    doc = {
        '_comment': [
            'NIP-060 section 5 spend vector, generated by contrib/p256/gen_spend_vector.py.',
            'Input 0 spends an AuthScript v1 output (authType 0x00) whose witness script is',
            '<ff01> OP_TXHASH 3 OP_TXFIELD OP_CAT 1 OP_TXFIELD OP_CAT <pubkey> OP_CHECKSIG_P256.',
            'The device signs digest = SHA-256(message), message = TXHASH || spent_script || amount.',
            'Input 1 is another input of the transaction, not signed here.',
        ],
        'privkey': '%064x' % priv,
        'pubkey': pub.hex(),
        'witness_script': script.hex(),
        'input_index': 0,
        'amount': amount,
        'spent_script': spent_spk.hex(),
        'unsigned_tx': unsigned,
        'txhash': p256_sign.txhash(tx, 0).hex(),
        'message': msg.hex(),
        'digest': digest.hex(),
        'signature': sig.hex(),
        'double_hash_signature': wrong.hex(),
        'signed_tx': signed,
    }
    json.dump(doc, sys.stdout, indent=1)
    sys.stdout.write('\n')


if __name__ == '__main__':
    main()
