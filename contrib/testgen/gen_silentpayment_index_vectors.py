"""Independent reference of the NIP-047 light client index format 1.

Usage: gen_silentpayment_index_vectors.py ../../src/test/data/silentpayment_index_vectors.json

The vectors are shared by the C++ unit tests and the neurai-silent-payments
JavaScript library. Nothing here comes from the C++ code.
"""
import hashlib
import json
import struct
import sys

P = 2**256 - 2**32 - 977
MAX_MONEY = 21000000000 * 100000000
G1 = "0279be667ef9dcbbac55a06295ce870b07029bfcdb2dce28d959f2815b16f81798"
G2 = "02c6047f9441ed7d6d3045406e95c07cd85c778e4b8cef3ca7abac09b95c709ee5"
G3 = "02f9308a019258c31049344f85f89d5229b531c845836f99b08601f113bce036f9"

# x = 0 is not on secp256k1: 7 is a quadratic non-residue modulo p.
assert pow(7, (P - 1) // 2, P) == P - 1


def tagged_hash(tag, msg):
    t = hashlib.sha256(tag.encode()).digest()
    return hashlib.sha256(t + t + msg).digest()


def compact(n):
    if n < 253:
        return bytes([n])
    if n <= 0xFFFF:
        return b"\xfd" + struct.pack("<H", n)
    if n <= 0xFFFFFFFF:
        return b"\xfe" + struct.pack("<I", n)
    return b"\xff" + struct.pack("<Q", n)


def internal(display_hex):
    return bytes.fromhex(display_hex)[::-1]


def h(fill):
    return fill * 32  # 64 hex chars


def block_bytes(b):
    out = internal(b["hash"]) + internal(b["prev"]) + struct.pack("<I", b["height"])
    out += compact(len(b["entries"]))
    for e in b["entries"]:
        out += internal(e["txid"]) + bytes.fromhex(e["tweak"]) + compact(len(e["outputs"]))
        for o in e["outputs"]:
            out += compact(o["vout"]) + bytes.fromhex(o["commitment"]) + struct.pack("<q", int(o["value_sat"]))
    out += compact(len(b["spent"]))
    for s in b["spent"]:
        out += internal(s["txid"]) + compact(s["vout"])
    return out


def envelope(msg_type, context):
    return b"NSPT" + bytes([1, msg_type]) + context


# Regtest-shaped context: network id 2, a genesis in display order, profile 0, family 3.
CONTEXT = bytes([2]) + bytes.fromhex("0f9188f13cb7b2c71f2a335e3a4fc328bf5beb436012afca590b1a11466e2206") + bytes([0, 3])

BLOCKS = [
    {
        "description": "empty block",
        "block": {"height": 1, "hash": h("11"), "prev": h("00"), "entries": [], "spent": []},
    },
    {
        "description": "two candidates, outputs with a 3-byte vout, spends with 5-byte vout",
        "block": {
            "height": 70123,
            "hash": "00000a" + "b3" * 29,
            "prev": "00000a" + "c4" * 29,
            "entries": [
                {
                    "txid": h("a1"),
                    "tweak": G1,
                    "outputs": [
                        {"vout": 0, "commitment": "5d" * 32, "value_sat": "150000000"},
                        {"vout": 300, "commitment": "6e" * 32, "value_sat": "1"},
                    ],
                },
                {
                    "txid": h("a2"),
                    "tweak": "03" + G2[2:],
                    "outputs": [{"vout": 1, "commitment": "7f" * 32, "value_sat": str(MAX_MONEY)}],
                },
            ],
            "spent": [{"txid": h("b1"), "vout": 1}, {"txid": h("b2"), "vout": 70000}],
        },
    },
    {
        "description": "one candidate, zero amount, no spends",
        "block": {
            "height": 4294967295,
            "hash": h("ee"),
            "prev": h("dd"),
            "entries": [{"txid": h("c1"), "tweak": G3, "outputs": [{"vout": 252, "commitment": "00" * 32, "value_sat": "0"}]}],
            "spent": [],
        },
    },
]

vectors = {
    "comment": "NIP-047 light client index, format 1. Generated by contrib/testgen/gen_silentpayment_index_vectors.py; "
               "shared by src/test/silentpaymentindex_tests.cpp and the neurai-silent-payments library.",
    "context": CONTEXT.hex(),
    "digest_tag": "NeuraiSilentPayments/v0/IndexBlock",
    "blocks": [],
    "messages": {},
    "invalid": [],
}

raw = []
for item in BLOCKS:
    data = block_bytes(item["block"])
    raw.append(data)
    vectors["blocks"].append({
        "description": item["description"],
        "block": item["block"],
        "bytes": data.hex(),
        "digest": tagged_hash("NeuraiSilentPayments/v0/IndexBlock", CONTEXT + data).hex(),
    })

vectors["messages"]["block"] = {
    "block_index": 1,
    "hex": (envelope(1, CONTEXT) + raw[1]).hex(),
}
range_header = {"snapshot_height": 70200, "snapshot_hash": h("f0"), "synced_height": 70200,
                "next_height": 70124, "status": 0}
vectors["messages"]["range"] = {
    "header": range_header,
    "block_indexes": [0, 1],
    "hex": (envelope(2, CONTEXT) + struct.pack("<I", 70200) + internal(h("f0")) + struct.pack("<I", 70200)
            + struct.pack("<I", 70124) + bytes([0]) + compact(2) + raw[0] + raw[1]).hex(),
}

base = raw[1]
head = base[:68]  # hash, prev, height
entry_tail = base[69:]


def one_entry(tweak, outputs):
    out = head + compact(1) + internal(h("a1")) + bytes.fromhex(tweak) + compact(len(outputs))
    for vout, value in outputs:
        out += compact(vout) + b"\x5d" * 32 + struct.pack("<q", value)
    return out + compact(0)


vectors["invalid"] = [
    {"description": "truncated", "bytes": base[:-1].hex(), "error": "truncated"},
    {"description": "non-minimal entry count", "bytes": (head + b"\xfd\x02\x00" + entry_tail).hex(),
     "error": "non-canonical compact size"},
    {"description": "tweak with prefix 04", "bytes": one_entry("04" + G1[2:], [(0, 1)]).hex(), "error": "invalid tweak"},
    {"description": "tweak not on the curve", "bytes": one_entry("02" + "00" * 32, [(0, 1)]).hex(), "error": "invalid tweak"},
    {"description": "entry without outputs", "bytes": one_entry(G1, []).hex(), "error": "entry without outputs"},
    {"description": "outputs out of order", "bytes": one_entry(G1, [(5, 1), (3, 1)]).hex(), "error": "outputs out of order"},
    {"description": "repeated vout", "bytes": one_entry(G1, [(3, 1), (3, 1)]).hex(), "error": "outputs out of order"},
    {"description": "amount above MAX_MONEY", "bytes": one_entry(G1, [(0, MAX_MONEY + 1)]).hex(), "error": "amount out of range"},
    {"description": "negative amount", "bytes": one_entry(G1, [(0, -1)]).hex(), "error": "amount out of range"},
    {"description": "entry count beyond the data", "bytes": (head + compact(200) + entry_tail).hex(), "error": "count out of range"},
    {"description": "vout above 2^32 - 1",
     "bytes": (head + compact(1) + internal(h("a1")) + bytes.fromhex(G1) + compact(1) + b"\xff" + struct.pack("<Q", 2**32)
               + b"\x5d" * 32 + struct.pack("<q", 1) + compact(0)).hex(),
     "error": "count out of range"},
    {"description": "trailing byte after a valid block", "bytes": (raw[0] + b"\x00").hex(), "error": "trailing bytes"},
]

path = sys.argv[1]
with open(path, "w") as f:
    json.dump(vectors, f, indent=2)
    f.write("\n")
print("wrote", path)
